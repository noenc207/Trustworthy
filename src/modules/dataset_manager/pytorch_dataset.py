"""
PyTorch Dataset Integration.
Consumes the unified labels generated by the Dataset Managers.
"""
from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset

from src.core.constants import IMAGE_MEAN, IMAGE_STD


class SkinLesionDataset(Dataset):
    """
    Standard PyTorch Dataset for Skin Lesion classification.
    Reads from the unified cleaned.csv generated by a BaseDatasetManager.
    """

    def __init__(
        self,
        cleaned_csv_path: str | Path,
        indices_csv_path: str | Path | None = None,
        transform: Callable | None = None,
        image_size: int = 224,
        return_metadata: bool = False,
    ) -> None:
        """
        Args:
            cleaned_csv_path: Path to `labels/cleaned.csv`.
            indices_csv_path: Optional path to a split indices file.
            transform: Optional albumentations or torchvision transform.
            image_size: Target image size.
            return_metadata: If True, returns a tuple of (img, class_id, metadata_dict).
        """
        self.df = pd.read_csv(cleaned_csv_path)
        self.transform = transform
        self.image_size = image_size
        self.return_metadata = return_metadata

        if indices_csv_path:
            indices_df = pd.read_csv(indices_csv_path, header=None, names=["image_id"])
            self.df = self.df.merge(indices_df, on="image_id", how="inner")

        self.records = self.df.to_dict("records")

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int) -> tuple | dict:
        record = self.records[idx]
        img_path = record["path"]
        class_id = int(record["class_id"])

        # Load image
        img = cv2.imread(img_path)
        if img is None:
            raise RuntimeError(f"Failed to load image at {img_path}")

        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        if self.transform:
            augmented = self.transform(image=img)
            img = augmented["image"]
            if not isinstance(img, torch.Tensor):
                img = self._default_transform(img)
        else:
            img = self._default_transform(img)

        if self.return_metadata:
            return img, class_id, record
        return img, class_id

    def _default_transform(self, img: np.ndarray) -> torch.Tensor:
        """Fallback deterministic transform if none provided."""
        img_resized = cv2.resize(img, (self.image_size, self.image_size))
        img_norm = img_resized.astype(np.float32) / 255.0
        img_norm = (img_norm - np.array(IMAGE_MEAN)) / np.array(IMAGE_STD)
        # HWC to CHW
        img_chw = np.transpose(img_norm, (2, 0, 1))
        return torch.from_numpy(img_chw).float()
