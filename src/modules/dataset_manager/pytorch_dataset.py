"""
PyTorch Dataset Integration.
Consumes the unified labels generated by the Dataset Managers.

SAFETY: This module NEVER silently loads the full dataset.
If a split manifest is expected but missing, it raises RuntimeError.
"""
from __future__ import annotations

import hashlib
from collections.abc import Callable
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset

from src.core.constants import NORMALIZE_MEAN, NORMALIZE_STD


class SkinLesionDataset(Dataset):
    """
    Standard PyTorch Dataset for Skin Lesion classification.
    Reads from the unified cleaned.csv generated by a BaseDatasetManager.
    
    SAFETY INVARIANT: If split_name is provided, indices_csv_path MUST be a valid
    path to a split manifest file. Silent full-dataset loading is IMPOSSIBLE.
    """

    def __init__(
        self,
        cleaned_csv_path: str | Path,
        indices_csv_path: str | Path | None = None,
        transform: Callable | None = None,
        image_size: int = 224,
        return_metadata: bool = False,
        split_name: str | None = None,
    ) -> None:
        self.split_name = split_name
        self.df = pd.read_csv(cleaned_csv_path)
        self.df = self.df.fillna("")
        self.transform = transform
        self.image_size = image_size
        self.return_metadata = return_metadata
        self._manifest_hash: str | None = None

        if indices_csv_path is not None:
            indices_path = Path(indices_csv_path)
            if not indices_path.exists():
                raise RuntimeError(
                    f"Split manifest file not found for split '{split_name}': {indices_path}. "
                    f"This is a FATAL error — the pipeline cannot proceed without explicit split manifests."
                )
            # Compute manifest hash for provenance tracking
            with open(indices_path, 'rb') as f:
                self._manifest_hash = hashlib.sha256(f.read()).hexdigest()
            
            indices_df = pd.read_csv(indices_path, header=None, names=["image_id"])
            self.df = self.df.merge(indices_df, on="image_id", how="inner")
        elif split_name is not None:
            # A split was requested but no manifest path was provided — FATAL
            raise RuntimeError(
                f"CRITICAL DATA INTEGRITY ERROR: Split '{split_name}' was requested but "
                f"no indices_csv_path was provided. This would silently load the ENTIRE dataset "
                f"({len(self.df)} samples) as the '{split_name}' split, causing catastrophic data leakage. "
                f"Refusing to proceed."
            )

        self.records = self.df.to_dict("records")

    @property
    def sample_ids(self) -> list[str]:
        """Return list of image_id values in this dataset."""
        return [r["image_id"] for r in self.records]

    @property
    def manifest_hash(self) -> str | None:
        """SHA256 hash of the split manifest file used to construct this dataset."""
        return self._manifest_hash

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int) -> tuple | dict:
        record = self.records[idx]
        img_path = record["path"]
        class_id = int(record["class_id"])

        # Load image
        img = cv2.imread(img_path)
        if img is None:
            raise RuntimeError(f"Failed to load image at {img_path}")

        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        if self.transform:
            augmented = self.transform(image=img)
            img = augmented["image"]
            if not isinstance(img, torch.Tensor):
                img = self._default_transform(img)
        else:
            img = self._default_transform(img)

        if self.return_metadata:
            return img, class_id, record
        return img, class_id

    def _default_transform(self, img: np.ndarray) -> torch.Tensor:
        """Fallback deterministic transform if none provided."""
        img_resized = cv2.resize(img, (self.image_size, self.image_size))
        img_norm = img_resized.astype(np.float32) / 255.0
        img_norm = (img_norm - np.array(NORMALIZE_MEAN)) / np.array(NORMALIZE_STD)
        # HWC to CHW
        img_chw = np.transpose(img_norm, (2, 0, 1))
        return torch.from_numpy(img_chw).float()
